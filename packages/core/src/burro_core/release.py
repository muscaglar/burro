"""The data release: its records, the protocol ranking reads it through, and the one parser.

A release is data and nothing else. `parse_release` and `open_release` do all
the checking, so the pipeline that writes a release and the API that loads one
cannot come to disagree about what a valid release is. Neither opens a file:
the caller reads the bytes and hands them over.

A release that is not made up is served only with what it was built with: its
evidence, its lock, and the hashes of the build. `open_served` holds the three
to each other. It reads none of the evidence. It is what keeps a release that
was changed after it was built, or that has no evidence at all, from being
served.
"""

