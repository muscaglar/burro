class Origin(Record):
    """Where one whole file came from, and when.

    The journeys and the stations of a preview may hold nothing, and then state
    no source and no date: there is nothing to cite. `sources_are_stated` says
    when. No fact is ever made from an origin that states none.
    """

    source_ids: SourceIdsIfAny
    as_of: DateOrMonthIfAny

    @property
    def stated(self) -> bool:
        return bool(self.source_ids) and self.as_of is not None


Ring = Annotated[tuple[Point, ...], Field(min_length=4)]
PolygonRings = Annotated[tuple[Ring, ...], Field(min_length=1)]


class Geometry(Record):
    """A GeoJSON geometry object: a polygon or a multipolygon, in WGS84."""

    type: GeometryType
    coordinates: PolygonRings | Annotated[tuple[PolygonRings, ...], Field(min_length=1)]

    @model_validator(mode="after")
    def _coordinates_suit_the_type(self) -> Self:
        # A polygon's first ring holds points; a multipolygon's first member holds rings.
        nested = isinstance(self.coordinates[0][0][0], tuple)
        if nested != (self.type is GeometryType.MULTI_POLYGON):
            raise ValueError("coordinates do not suit the geometry type")
        return self


class AreaGeometry(Record):
    area_id: AreaId
    geometry: Geometry


class Cutoffs(Record):
    """The longest journey the release routed, by mode. Anything longer is `beyond_cutoff`."""

    # No shorter than the shortest cap a commute may have, so every mode can be asked for.
    pt: int = Field(ge=10, le=1440)
    cycle: int = Field(ge=10, le=1440)
    walk: int = Field(ge=10, le=1440)

    def of(self, mode: Mode) -> int:
        return {Mode.PT: self.pt, Mode.CYCLE: self.cycle, Mode.WALK: self.walk}[mode]


class TravelTable(Record):
    """`travel.json` as it is written: four matrices, rows by area and columns by destination.

    A cell is minutes, `-1` for no journey within the cutoff, or `None` for not
    computed. The two spellings exist only here; `Release.travel()` returns a
    `Travel` and nothing outside this module sees a `-1`.
    """

    # Both are empty only in a preview that holds no journey: `sources_are_stated`.
    source_ids: SourceIdsIfAny
    as_of: DateOrMonthIfAny
    area_ids: tuple[AreaId, ...]
    destination_ids: tuple[DestinationId, ...]
    cutoff_minutes: Cutoffs
    pt_typical: Matrix
    pt_just_missed: Matrix
    cycle: Matrix
    walk: Matrix

    def matrix(self, mode: Mode, basis: PtBasis) -> Matrix:
        if mode is Mode.CYCLE:
            return self.cycle
        if mode is Mode.WALK:
            return self.walk
        return self.pt_typical if basis is PtBasis.TYPICAL else self.pt_just_missed


class Release(Protocol):
    """What ranking, facts and the interpreters read a release through.

    The three tuples are ordered by id, and `stations` nearest first. `vibes`
    holds the vibes this release carries, in the order of the shelf. `None`
    means the id is unknown to this release, or for `cost` that there is no
    estimate. `travel` never returns `None`: for a time that is not in the
    release, and for an id it does not know, it answers `missing`.

    `placed` and `costed` say what the release can answer at all. A vibe is
    placed where some area has a band for it, and a kind of home is costed
    where some area has an estimate for it. A wish for what is neither is
    turned away as `not_in_release` and never ranked on: every area would
    lack it, and none would be left to rank.
    """

    @property
    def manifest(self) -> Manifest: ...
    @property
    def neighbourhoods(self) -> tuple[Neighbourhood, ...]: ...
    @property
    def metrics(self) -> tuple[Metric, ...]: ...
    @property
    def places(self) -> tuple[Place, ...]: ...
    @property
    def vibes(self) -> tuple[Tag, ...]: ...
    def neighbourhood(self, area_id: str) -> Neighbourhood | None: ...
    def geometry(self, area_id: str) -> Geometry | None: ...
    def feature(self, area_id: str, feature_id: FeatureId) -> FeatureValue | None: ...
    def tag(self, area_id: str, tag_id: TagId) -> TagValue | None: ...
    def cost(self, area_id: str, tenure: Tenure, segment: Segment) -> CostEstimate | None: ...
    def place(self, place_id: str) -> Place | None: ...
    def travel(self, area_id: str, destination_id: str, mode: Mode, basis: PtBasis) -> Travel: ...
    def stations(self, area_id: str) -> tuple[StationAccess, ...]: ...
    def origin(self, part: Part) -> Origin: ...
    def cutoff(self, mode: Mode) -> int: ...
    def placed(self, tag_id: TagId) -> bool: ...
    def costed(self, tenure: Tenure, segment: Segment) -> bool: ...


class WaitsOn(Record):
    """A part of a recipe that a release carries no measure for. It is named, never filled in."""

    feature_id: FeatureId
    # The name of the measure, as the catalogue gives it.
    label: str
    hundredths: int = Field(ge=1, le=100)


class RecipeHeld(Record):
    """How much of one vibe's recipe a release carries, and what the vibe waits on.

    It is of the release and of no area. An area may have a figure for fewer
    parts than the release carries, and its own fact says so.
    """

    tag_id: TagId
    # The hundredths of the recipe that the release carries a measure for.
    held: int = Field(ge=0, le=100)
    # The least an area must have a figure for, in hundredths, to be given a band.
    needed: int = Field(ge=1, le=100)
    # Whether any area has a band. Where none has, a wish for the vibe is
    # turned away as `not_in_release`.
    placed: StrictBool
    # The parts the release carries no measure for, in the order of the recipe.
    waits_on: tuple[WaitsOn, ...]


def recipes_held(release: Release) -> tuple[RecipeHeld, ...]:
    """What the release holds of each vibe it carries, in the order of the shelf."""
    carried = {metric.feature_id for metric in release.metrics}
    return tuple(
        RecipeHeld(
            tag_id=vibe.tag_id,
            held=sum(term.hundredths for term in vibe.terms if term.feature_id in carried),
            needed=TAG_MIN_COVERAGE_HUNDREDTHS,
            placed=release.placed(vibe.tag_id),
            waits_on=tuple(
                WaitsOn(
                    feature_id=term.feature_id,
                    label=FEATURES[term.feature_id].label,
                    hundredths=term.hundredths,
                )
                for term in vibe.terms
                if term.feature_id not in carried
            ),
        )
        for vibe in release.vibes
    )


def _station_order(row: StationAccess) -> tuple[str, bool, int, str]:
    return (row.area_id, not row.nearest, row.walk_minutes, row.station_id)


def _shelf_order(tag: Tag) -> tuple[int, str]:
    return (tag.shelf_order or 0, tag.tag_id)


@dataclass(frozen=True)
class InMemoryRelease:
    """A whole release held as records. The one implementation of `Release` in this build.

    Every tuple is put in one order on construction, so two releases built from
    the same rows in a different order are equal and are written the same. The
    constructor checks nothing: `parse_release` does, and a release built by
    hand in a test is as good as its author.
    """

    manifest: Manifest
    neighbourhoods: tuple[Neighbourhood, ...]
    neighbourhoods_origin: Origin
    travel_table: TravelTable
    stations_origin: Origin
    metrics: tuple[Metric, ...] = ()
    features: tuple[FeatureValue, ...] = ()
    tags: tuple[TagValue, ...] = ()
    costs: tuple[CostEstimate, ...] = ()
    destinations: tuple[Destination, ...] = ()
    places: tuple[Place, ...] = ()
    station_rows: tuple[StationAccess, ...] = ()
    geometries: tuple[AreaGeometry, ...] = ()
    vibes: tuple[Tag, ...] = ()

    _areas: Mapping[str, Neighbourhood] = field(init=False, repr=False, compare=False)
    _geometries: Mapping[str, Geometry] = field(init=False, repr=False, compare=False)
    _features: Mapping[tuple[str, FeatureId], FeatureValue] = field(
        init=False, repr=False, compare=False
    )
    _tags: Mapping[tuple[str, TagId], TagValue] = field(init=False, repr=False, compare=False)
    _costs: Mapping[tuple[str, Tenure, Segment], CostEstimate] = field(
        init=False, repr=False, compare=False
    )
    _places: Mapping[str, Place] = field(init=False, repr=False, compare=False)
    _stations: Mapping[str, tuple[StationAccess, ...]] = field(
        init=False, repr=False, compare=False
    )
    _rows: Mapping[str, int] = field(init=False, repr=False, compare=False)
    _columns: Mapping[str, int] = field(init=False, repr=False, compare=False)
    _placed: frozenset[TagId] = field(init=False, repr=False, compare=False)
    _costed: frozenset[tuple[Tenure, Segment]] = field(init=False, repr=False, compare=False)

    def __post_init__(self) -> None:
        put = object.__setattr__
        put(self, "neighbourhoods", tuple(sorted(self.neighbourhoods, key=lambda n: n.area_id)))
        put(self, "metrics", tuple(sorted(self.metrics, key=lambda m: m.feature_id)))
        put(self, "features", tuple(sorted(self.features, key=lambda f: (f.area_id, f.feature_id))))
        put(self, "tags", tuple(sorted(self.tags, key=lambda t: (t.area_id, t.tag_id))))
        put(
            self,
            "costs",
            tuple(sorted(self.costs, key=lambda c: (c.area_id, c.tenure, c.segment))),
        )
        put(self, "destinations", tuple(sorted(self.destinations, key=lambda d: d.destination_id)))
        put(self, "places", tuple(sorted(self.places, key=lambda p: p.place_id)))
        put(self, "station_rows", tuple(sorted(self.station_rows, key=_station_order)))
        put(self, "geometries", tuple(sorted(self.geometries, key=lambda g: g.area_id)))
        put(self, "vibes", tuple(sorted(self.vibes, key=_shelf_order)))

        put(self, "_areas", {n.area_id: n for n in self.neighbourhoods})
        put(self, "_geometries", {g.area_id: g.geometry for g in self.geometries})
        put(self, "_features", {(f.area_id, f.feature_id): f for f in self.features})
        put(self, "_tags", {(t.area_id, t.tag_id): t for t in self.tags})
        put(self, "_costs", {(c.area_id, c.tenure, c.segment): c for c in self.costs})
        put(self, "_places", {p.place_id: p for p in self.places})
        stations: dict[str, list[StationAccess]] = {}
        for row in self.station_rows:
            stations.setdefault(row.area_id, []).append(row)
        put(self, "_stations", {area_id: tuple(rows) for area_id, rows in stations.items()})
        put(self, "_rows", {a: i for i, a in enumerate(self.travel_table.area_ids)})
        put(self, "_columns", {d: i for i, d in enumerate(self.travel_table.destination_ids)})
        put(self, "_placed", frozenset(t.tag_id for t in self.tags if t.score is not None))
        put(self, "_costed", frozenset((c.tenure, c.segment) for c in self.costs))

    def neighbourhood(self, area_id: str) -> Neighbourhood | None:
        return self._areas.get(area_id)

    def geometry(self, area_id: str) -> Geometry | None:
        return self._geometries.get(area_id)

    def feature(self, area_id: str, feature_id: FeatureId) -> FeatureValue | None:
        return self._features.get((area_id, feature_id))

    def tag(self, area_id: str, tag_id: TagId) -> TagValue | None:
        return self._tags.get((area_id, tag_id))

    def cost(self, area_id: str, tenure: Tenure, segment: Segment) -> CostEstimate | None:
        return self._costs.get((area_id, tenure, segment))

    def place(self, place_id: str) -> Place | None:
        return self._places.get(place_id)

    def travel(self, area_id: str, destination_id: str, mode: Mode, basis: PtBasis) -> Travel:
        row = self._rows.get(area_id)
        column = self._columns.get(destination_id)
        if row is None or column is None:
            return MISSING_TRAVEL
        matrix = self.travel_table.matrix(mode, basis)
        # A hand-built release may hold a matrix smaller than its ids say.
        if row >= len(matrix) or column >= len(matrix[row]):
            return MISSING_TRAVEL
        cell = matrix[row][column]
        if cell is None:
            return MISSING_TRAVEL
        if cell == BEYOND_CUTOFF_CELL:
            return BEYOND_CUTOFF_TRAVEL
        return Travel(status=TravelStatus.OK, minutes=cell)

    def stations(self, area_id: str) -> tuple[StationAccess, ...]:
        return self._stations.get(area_id, ())

    def origin(self, part: Part) -> Origin:
        if part is Part.NEIGHBOURHOODS:
            return self.neighbourhoods_origin
        if part is Part.STATIONS:
            return self.stations_origin
        return Origin(source_ids=self.travel_table.source_ids, as_of=self.travel_table.as_of)

    def cutoff(self, mode: Mode) -> int:
        return self.travel_table.cutoff_minutes.of(mode)

    def placed(self, tag_id: TagId) -> bool:
        return tag_id in self._placed

    def costed(self, tenure: Tenure, segment: Segment) -> bool:
        return (tenure, segment) in self._costed

    def documents(self) -> dict[str, object]:
        """The content of every file of this release, keyed by file name.

        The inverse of `parse_release`. Writing a release is serialising these,
        so the shape of a file is stated in one module and not two.
        """
        files = _Files(
            manifest=self.manifest,
            # The areas of a release always say where they came from. One built by hand
            # that does not is refused here, as any record that is not valid is.
            neighbourhoods=_NeighbourhoodsFile.model_validate(
                {
                    "source_ids": self.neighbourhoods_origin.source_ids,
                    "as_of": self.neighbourhoods_origin.as_of,
                    "neighbourhoods": self.neighbourhoods,
                }
            ),
            geometry=_GeometryFile(
                type="FeatureCollection",
                features=tuple(
                    _GeometryFeature(
                        type="Feature",
                        id=g.area_id,
                        properties=_GeometryProperties(area_id=g.area_id),
                        geometry=g.geometry,
                    )
                    for g in self.geometries
                ),
            ),
            catalogue=_CatalogueFile(
                catalogue_version=CATALOGUE_VERSION, metrics=self.metrics, vibes=self.vibes
            ),
            features=_FeaturesFile(rows=self.features),
            tags=_TagsFile(rows=self.tags),
            cost=_CostFile(rows=self.costs),
            destinations=_DestinationsFile(destinations=self.destinations),
            travel=self.travel_table,
            stations=_StationsFile(
                source_ids=self.stations_origin.source_ids,
                as_of=self.stations_origin.as_of,
                rows=self.station_rows,
            ),
            places=_PlacesFile(places=self.places),
        )
        return {name: model.model_dump(mode="json") for name, model in files.by_name().items()}


