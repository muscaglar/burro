def _imports(path: Path) -> set[str]:
    found: set[str] = set()
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Import):
            found |= {alias.name for alias in node.names}
        elif isinstance(node, ast.ImportFrom):
            found.add(node.module or "")
            found |= {f"{node.module}.{alias.name}" for alias in node.names}
    return found


def test_nothing_in_core_imports_household_income():
    for path in sorted(SOURCE.glob("*.py")):
        if path.stem == "income":
            continue
        assert not [name for name in _imports(path) if "income" in name], path.name
    assert not [name for name in burro_core.__all__ if "income" in name.casefold()]


def test_household_income_imports_nothing_of_core_that_ranks_or_says():
    ours = {name for name in _imports(SOURCE / "income.py") if name.startswith("burro_core")}
    modules = {name for name in ours if name.count(".") == 1}
    assert modules == {"burro_core._record", "burro_core.ids"}
    # Of the ids it takes the form of an id and nothing of the vocabulary.
    taken = {name.rsplit(".", 1)[1] for name in ours if name.count(".") == 2}
    assert not taken & {"FeatureId", "TagId", "FactKind", "Dimension", "TemplateId", "Segment"}


def test_a_release_cannot_return_household_income():
    members = [name for name in dir(Release) if not name.startswith("_")]
    assert members and not [name for name in members if "income" in name or "earn" in name]
    for name, hint in get_type_hints(InMemoryRelease.__init__).items():
        assert "income" not in name and "income" not in str(hint).casefold(), name
    assert not hasattr(fixture_release(), "income")


def test_a_release_folder_that_holds_a_file_of_income_is_refused():
    assert INCOME not in DATA_FILES
    folder = REPOSITORY / "data" / "fixtures" / "synthetic" / RELEASE_ID
    held = {f.name: f.read_bytes() for f in sorted(folder.iterdir()) if f.name != ".DS_Store"}
    held[INCOME] = files()[INCOME]
    with pytest.raises(ReleaseError) as caught:
        open_release(RELEASE_ID, held)
    assert (caught.value.file, caught.value.rule) == (INCOME, "files_match_manifest")


VOCABULARY = (
    FeatureId,
    TagId,
    FactKind,
    TemplateId,
    Dimension,
    Describes,
    Setting,
    UnmetCategory,
    Segment,
)
NAMES_INCOME = frozenset(
    {"income", "incomes", "earn", "earns", "earnings", "salary", "wage", "pay"}
)


def _parts(value: str) -> set[str]:
    return set(re.split(r"[^a-z0-9]+", value.casefold()))


@pytest.mark.parametrize("vocabulary", VOCABULARY, ids=lambda each: each.__name__)
def test_no_word_of_the_vocabulary_names_income(vocabulary: Any):
    """A spec, an edit, a fact and a sentence are made of these, so none can name it."""
    for member in vocabulary:
        assert not _parts(member.value) & NAMES_INCOME, member


@pytest.mark.parametrize("record", [PreferenceSpec, Operations], ids=lambda each: each.__name__)
def test_no_spec_and_no_edit_has_a_field_for_income(record: Any):
    assert not _parts(json.dumps(record.model_json_schema())) & NAMES_INCOME
    # A field a record does not know is refused, so none can be added by whoever sends one.
    sent = default_spec(Tenure.BUY).model_dump(mode="json") | {"income": {"at_least": 50_000}}
    with pytest.raises(ValueError, match="income"):
        PreferenceSpec.model_validate(sent)


def test_household_income_is_never_handed_a_release():
    """It is told the release's id, whether it is made up, and its areas. It is handed no more."""
    for function in (open_income, parse_income, shown, offer):
        hints = get_type_hints(function)
        assert not [name for name, hint in hints.items() if "Release" in str(hint)], function


@pytest.mark.parametrize(
    "text",
    ["high income", "a high income area", "household income", "well paid", "good salaries"],
)
def test_the_reader_makes_no_edit_and_no_offer_from_a_word_for_income(text: str):
    """No word for what people earn is read as a wish. It weighs nothing, and offers nothing."""
    for tenure in Tenure:
        asked = InterpretRequest(text=text, spec=default_spec(tenure), release=small_release())
        result = RuleInterpreter().interpret(asked)
        assert not result.operations.weight_ops and not result.operations.tag_ops
        assert result.operations.budget_ops == ()
        assert result.suggestions == ()


