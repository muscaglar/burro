def refusal(held: dict[str, bytes], folder: str = FOLDER, **given: Any) -> IncomeError:
    with pytest.raises(IncomeError) as caught:
        open_income(
            folder,
            held,
            given.get("release_id", RELEASE_ID),
            given.get("synthetic", True),
            given.get("area_ids", AREAS),
        )
    # A refusal names the file, the row and the rule, and never a value.
    assert not re.search(r"[0-9]{4,}", str(caught.value).replace(RELEASE_ID, ""))
    return caught.value


def broken(change: Break) -> IncomeError:
    held = copy.deepcopy(document())
    change(held)
    return refusal(files(held))


def test_a_folder_that_is_not_named_for_the_release_is_refused():
    assert refusal(files(), folder="syn-2026-09-23-02-income").rule == (
        "folder_is_named_for_the_release"
    )
    assert refusal(files(), folder=f"{RELEASE_ID}-residents").rule == (
        "folder_is_named_for_the_release"
    )


def test_a_file_that_is_missing_extra_or_changed_is_refused():
    assert refusal({MANIFEST: files()[MANIFEST]}).file == INCOME
    assert refusal({INCOME: files()[INCOME]}).file == MANIFEST
    extra = refusal(files() | {"notes.txt": b"x"})
    assert (extra.file, extra.rule) == ("notes.txt", "files_match_manifest")
    changed = files()
    changed[INCOME] = changed[INCOME].replace(b"52300", b"52301")
    assert (refusal(changed).file, refusal(changed).rule) == (INCOME, "files_match_manifest")


def test_figures_made_for_another_release_or_said_to_be_real_are_refused():
    assert refusal(files(), release_id="syn-2026-09-23-02", folder="syn-2026-09-23-02-income").rule
    assert refusal(files(), synthetic=False).rule == "income_is_of_the_release"
    assert broken(lambda held: held.update(release_id="syn-2026-09-23-02")).rule in {
        "income_is_of_the_release",
        "files_match_manifest",
    }


def set_in(*path: str | int, **changes: Any) -> Break:
    """A change that sets fields of what stands at `path` of the document."""

    def change(held: Document) -> None:
        found: Any = held
        for step in path:
            found = found[step]
        found.update(changes)

    return change


def drop_the_last(held: Document) -> None:
    held["areas"].pop()


def turn_round(held: Document) -> None:
    held["areas"].reverse()


def say_twice(held: Document) -> None:
    held["areas"].append(dict(held["areas"][0]))


BROKEN: list[tuple[Break, str]] = [
    (set_in("source", source_id="ons-income-estimates-small-areas"), "made_up_is_said"),
    (set_in("source", url="https://example.org/"), "made_up_is_said"),
    (set_in("areas", 0, area_id="lon-n0001"), "made_up_is_said"),
    (drop_the_last, "areas_are_the_releases"),
    (turn_round, "areas_are_the_releases"),
    (say_twice, "areas_are_the_releases"),
    (set_in("areas", 0, lower=60_000), "limits_hold_the_estimate"),
    (set_in("areas", 0, upper=50_000), "limits_hold_the_estimate"),
    (set_in("areas", 0, lower=None), "limits_hold_the_estimate"),
    (set_in("areas", 2, estimate=40_000), "limits_hold_the_estimate"),
    (set_in(end="2023-04"), "year_is_a_year"),
    (set_in(start="2021-04"), "year_is_a_year"),
    (set_in("areas", 0, estimate=0), "shape_is_valid"),
    (set_in("areas", 0, estimate=52_300.5), "shape_is_valid"),
    (set_in("areas", 0, estimate="52300"), "shape_is_valid"),
    # Nothing can be put beside a figure: a field the record does not know is refused.
    (set_in("areas", 0, percentile=71), "shape_is_valid"),
    (set_in("areas", 0, rank=1), "shape_is_valid"),
    (set_in(city={"estimate": 50_000}), "shape_is_valid"),
    (set_in(end="March 2023"), "shape_is_valid"),
]


@pytest.mark.parametrize(("change", "rule"), BROKEN)
def test_figures_that_break_a_rule_are_refused_and_the_rule_is_named(change: Break, rule: str):
    assert broken(change).rule == rule


def test_a_file_that_is_no_json_is_refused():
    held = files()
    for content in (b"{", b"\xff\xfe", b'{"areas": NaN}'):
        bad = dict(held) | {INCOME: content}
        manifest = json.loads(held[MANIFEST]) | {
            "income_sha256": hashlib.sha256(content).hexdigest(),
            "income_bytes": len(content),
        }
        bad[MANIFEST] = as_bytes(manifest)
        assert refusal(bad).rule == "json_is_valid"


