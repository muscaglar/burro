def test_the_figure_is_the_publishers_estimate_with_both_its_limits_in_words():
    found = of()
    assert (found.estimate, found.lower, found.upper) == ("£52,300", "£46,100", "£59,300")
    # Both limits are served as they are printed, so that no client joins two figures.
    assert found.limits == "£46,100 to £59,300"
    assert found.none_given is None
    # A figure is said as it is to be printed, so no client works one out or rounds one.
    assert pounds(1_234_567) == "£1,234,567" == of(1).estimate


def test_it_says_the_year_it_is_of_and_that_it_is_from_a_model():
    found = of()
    assert found.year_line == "A made-up year ending March 2023: April 2022 to March 2023."
    assert "model" in found.modelled and "model" in ONS.modelled
    assert ONS.year_line.format(start="April 2022", end="March 2023") == (
        "Financial year ending March 2023: April 2022 to March 2023."
    )
    assert (month_in_words("2023-03"), day_in_words("2026-09-24")) == (
        "March 2023",
        "24 September 2026",
    )


