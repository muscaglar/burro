def document() -> Document:
    """The made-up figures of three areas: two with an estimate, and one with none."""
    return {
        "release_id": RELEASE_ID,
        "synthetic": True,
        "start": "2022-04",
        "end": "2023-03",
        "source": dict(MADE_UP_SOURCE),
        "areas": [
            {"area_id": AREAS[0], "estimate": 52_300, "lower": 46_100, "upper": 59_300},
            {"area_id": AREAS[1], "estimate": 1_234_567, "lower": 1_234_567, "upper": 1_234_567},
            {"area_id": AREAS[2], "estimate": None, "lower": None, "upper": None},
        ],
    }


def as_bytes(held: object) -> bytes:
    return json.dumps(held, sort_keys=True, separators=(",", ":")).encode()


def files(held: Document | None = None) -> dict[str, bytes]:
    content = as_bytes(document() if held is None else held)
    manifest = {
        "release_id": RELEASE_ID,
        "synthetic": True,
        "income_sha256": hashlib.sha256(content).hexdigest(),
        "income_bytes": len(content),
        "source": (document() if held is None else held)["source"],
    }
    return {INCOME: content, MANIFEST: as_bytes(manifest)}


def opened(held: Document | None = None) -> Income:
    return open_income(FOLDER, files(held), RELEASE_ID, True, AREAS)


def of(area: int = 0) -> IncomeShown:
    found = shown(opened(), AREAS[area])
    assert found is not None
    return found


