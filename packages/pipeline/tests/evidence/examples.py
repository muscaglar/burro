import hashlib

from burro_pipeline.evidence.claim import (
    Claim,
    ClaimKind,
    Derived,
    FoundBy,
    Review,
    Reviewer,
    ReviewStatus,
    claim_id_of,
    text_sha256,
)
from burro_pipeline.evidence.method import Kind, Method
from burro_pipeline.evidence.receipt import Geography, Period, made_up_receipt
from burro_pipeline.evidence.record import MADE_UP_SOURCE
from burro_pipeline.evidence.row import EvidenceRow, Flag, State
from burro_pipeline.registry.model import Use

RETRIEVED_AT = "2026-09-23T09:12:31Z"
RELEASE_ID = "syn-2026-09-23-01"
AREA_ID = "syn-n0001"

# The receipt of a file of parks, and of the file of homes that a walk is weighted by.
RECEIPT = made_up_receipt(
    "made-up-parks.gpkg", Use.SCORING, Geography.POLYGON, Period(as_at="2025-04"), RETRIEVED_AT
)
HOMES = made_up_receipt(
    "made-up-homes.csv", Use.SCORING, Geography.OA21, Period(as_at="2021-03-21"), RETRIEVED_AT
)

METHOD = Method(
    derivation_id="walk_to_nearest@1",
    sentence="The walk from homes to the nearest park of 2 hectares or more, taken as the "
    "median by homes and rounded to 10 metres.",
    kind=Kind.MEASURED,
    parameters={"hectares": 2, "rounded_to_metres": 10},
    code="burro_pipeline.derive.walk",
)

ROW = EvidenceRow(
    fact_id=f"{AREA_ID}/feature/park_proximity",
    derivation_id=METHOD.derivation_id,
    inputs=tuple(sorted((RECEIPT.file_id, HOMES.file_id))),
    data_period=Period(start="2021-03-21", end="2025-04-30"),
    retrieved_on="2026-09-23",
    units_used=10,
    units_expected=11,
    weight_covered=0.97,
    state=State.PARTIAL,
    flags=(Flag.UNIT_SPLIT,),
    value=290.0,
)

